"""Alembic 迁移：新库结构与模型一致；旧库（无版本表）可升级。"""
from __future__ import annotations

import sqlite3

from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected

from app.database import alembic_config, engine


def test_schema_matches_models(app):
    try:
        command.check(alembic_config())
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - 失败时给出差异
        raise AssertionError(f"模型与迁移不一致：{exc}") from exc


def test_upgrade_is_idempotent(app):
    command.upgrade(alembic_config(), "head")
    with engine.connect() as conn:
        version = conn.exec_driver_sql("SELECT version_num FROM alembic_version").scalar()
    assert version


def test_legacy_database_without_version_table(tmp_path, monkeypatch):
    """模拟引入 Alembic 之前的旧库：缺列、缺表、没有 alembic_version。"""
    db_path = tmp_path / "legacy.db"
    conn = sqlite3.connect(db_path)
    conn.executescript(
        """
        CREATE TABLE accounts (id INTEGER PRIMARY KEY, email VARCHAR(320) NOT NULL UNIQUE,
            display_name VARCHAR(255), encrypted_password TEXT NOT NULL, enabled BOOLEAN NOT NULL,
            created_at DATETIME NOT NULL, updated_at DATETIME NOT NULL);
        CREATE TABLE messages (id INTEGER PRIMARY KEY, account_id INTEGER NOT NULL,
            folder VARCHAR(255) NOT NULL, uid INTEGER NOT NULL, message_id VARCHAR(998),
            subject TEXT, from_addr TEXT, to_addr TEXT, cc_addr TEXT, bcc_addr TEXT, date DATETIME,
            body_text TEXT, body_html TEXT, is_read BOOLEAN NOT NULL, has_attachments BOOLEAN NOT NULL,
            created_at DATETIME NOT NULL, UNIQUE(account_id, folder, uid));
        CREATE TABLE attachments (id INTEGER PRIMARY KEY, message_id INTEGER NOT NULL,
            filename VARCHAR(512) NOT NULL, mime_type VARCHAR(255) NOT NULL, size INTEGER NOT NULL,
            is_inline BOOLEAN NOT NULL, content_id VARCHAR(255), file_path TEXT NOT NULL,
            public_url TEXT NOT NULL, created_at DATETIME NOT NULL);
        CREATE TABLE login_throttle (id INTEGER PRIMARY KEY, ip_address VARCHAR(255) NOT NULL UNIQUE,
            failed_attempts INTEGER NOT NULL, last_failed_at DATETIME, blocked_until DATETIME,
            created_at DATETIME NOT NULL, updated_at DATETIME NOT NULL);
        INSERT INTO accounts VALUES (1, 'a@example.com', NULL, 'x', 1, '2026-01-01', '2026-01-01');
        INSERT INTO messages VALUES (1, 1, '[Gmail]/Sent Mail', 7, NULL, 's', NULL, NULL, NULL, NULL,
            NULL, 'b', NULL, 0, 0, '2026-01-01');
        """
    )
    conn.commit()
    conn.close()

    from sqlalchemy import create_engine

    legacy_engine = create_engine(f"sqlite:///{db_path.as_posix()}")
    cfg = alembic_config()
    with legacy_engine.connect() as connection:
        cfg.attributes["connection"] = connection
        command.upgrade(cfg, "head")

    conn = sqlite3.connect(db_path)
    cols = {row[1] for row in conn.execute("PRAGMA table_info(messages)")}
    assert "folder_kind" in cols
    assert conn.execute("SELECT folder_kind FROM messages WHERE id = 1").fetchone()[0] == "sent"
    tables = {row[0] for row in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}
    assert {"trusted_senders", "blocked_senders", "sync_state", "alembic_version"} <= tables
    conn.close()
